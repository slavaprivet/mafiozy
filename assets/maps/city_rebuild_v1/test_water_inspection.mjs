import assert from 'node:assert/strict';
import {createLandscapePlan} from './landscape_plan.mjs';
import {findWaterJumpInspection,createWaterImpactCapture} from './water_inspection.mjs';
const terrain=createLandscapePlan(),before=terrain.grid.heights.slice();
const entry=findWaterJumpInspection(terrain,(x,z)=>terrain.canWalk(x,z));
assert(entry);assert(!terrain.waterAt(entry.origin.x,entry.origin.z));
assert(terrain.waterAt(entry.landing.x,entry.landing.z).depth>.18);
assert.equal(findWaterJumpInspection(terrain,()=>false),null);
assert.deepEqual(terrain.grid.heights,before);
const capture=createWaterImpactCapture();
assert.equal(capture.update(.04,10),false,'normal gameplay never pauses');
capture.arm(10);
for(let i=0;i<100;i++)assert.equal(capture.update(.04,10),false,'standing water never triggers capture');
assert.equal(capture.update(.04,11),false);
assert.equal(capture.update(.04,11),false);
assert.equal(capture.update(.04,11),false);
assert.equal(capture.update(.04,11),true,'captures real impact once droplets have risen');
assert.equal(capture.paused,true);assert.equal(capture.update(.04,12),false);
capture.reset();assert.equal(capture.paused,false);
capture.arm(12);capture.update(NaN,13);assert.equal(capture.paused,false);
capture.reset();assert.equal(capture.update(1,15),false);
console.log(JSON.stringify({passed:true,entry}));
