import assert from 'node:assert/strict';
import {createNpcNativePerception,perceptionBodyBlocks} from './npc_native_perception.mjs';
import {createWalkCollisionIndex} from './walk_collision_index.mjs';
const wall={polygonCR:[[3.99,3.99],[4.01,3.99],[4.01,4.01],[3.99,4.01]],minYM:0,maxYM:4};
let index=createWalkCollisionIndex([[wall]]),floor=()=>0,loaded=true;
const car={object:{visible:true,position:{x:20.5,y:0,z:0},scale:{x:1,y:1,z:1},rotation:{y:.45}},profile:{halfWidth:1,halfLength:2,height:2.1}};
let cars=[];
const los=createNpcNativePerception({bodiesAt:(c,r)=>index(c,r),groundHeight:(x,z)=>floor(x,z),getVehicles:()=>cars,ready:()=>loaded});
const q={fromR:0,fromC:0,toR:8,toC:8};
assert.equal(los.query(q).blocked,true,'thin native wall on a broadphase corner');
assert.equal(los.query({...q,fromR:8,toR:0}).blocked,true,'opposite diagonal');
assert.equal(los.query({...q,toC:0}).blocked,false,'nearby wall does not block another ray');
wall.maxYM=.6;assert.equal(los.query(q).blocked,false,'eyes see over low bench');
assert.equal(los.query({...q,eyeHeight:.35,targetHeight:.35}).blocked,true,'prone sight intersects the same bench');
wall.minYM=2;wall.maxYM=4;assert.equal(los.query(q).blocked,false,'overhead canopy leaves view below');
wall.minYM=0;wall.maxYM=4;
index=createWalkCollisionIndex([]);assert.equal(los.query(q).blocked,false,'removed/opened native obstacle updates immediately');
cars=[car];los.beginFrame();const straight={...q,toR:0,toC:10};
assert.equal(los.query(straight).blocked,true,'current rotated vehicle blocks sight');
car.object.position.z=20;los.beginFrame();assert.equal(los.query(straight).blocked,false,'moving car does not leave stale occlusion');
cars=[];los.beginFrame();floor=x=>x>18&&x<23?3:0;
assert.equal(los.query(straight).blocked,true,'terrain ridge interrupts sight');
loaded=false;assert.equal(los.query(q),null,'unloaded native map does not suppress source fallback');
assert.equal(perceptionBodyBlocks({polygonCR:[[0,0],[1,0],[1,1],[0,1]],minYM:2,maxYM:3},{r:.5,c:-1,y:0},{r:.5,c:2,y:6}),true,'vertical slab intersects within polygon');
console.log('Native NPC perception: walls, thin corners, posture, overhead, vehicles, terrain PASS');
