import assert from 'node:assert/strict';
import {createTireTrackPool} from './tire_tracks.mjs';
const car={x:0,z:0,yaw:0,speed:12,frontSlip:0,rearSlip:1};
const pool=createTireTrackPool({maxSegments:12,lifetime:2});
pool.update(car,.02);pool.update({...car,z:.5},.02);
assert.equal(pool.active,2,'only the two locked rear wheels leave marks');
assert.equal(pool.positions.length,12*18);
const opacity=pool.opacity[0];pool.update(null,1.5);
assert(pool.opacity[0]>0&&pool.opacity[0]<opacity,'marks gradually fade');
pool.update(null,.6);assert.equal(pool.active,0,'all marks expire');assert(pool.opacity.every(v=>v===0));
pool.clear();for(let i=0;i<100;i++)pool.update({...car,z:i*.5},.02);
assert.equal(pool.count,12);assert.equal(pool.active,12,'ring buffer remains bounded during a long skid');
pool.clear();pool.update(car,.02);pool.update({...car,z:100},.02);
assert.equal(pool.count,0,'teleport does not connect marks across city');
pool.update({...car,z:100.5,frontSlip:0,rearSlip:0},.02);
pool.update({...car,z:101},.02);assert.equal(pool.count,0,'release and reapply do not bridge an unmarked gap');
pool.update({...car,z:101.5},.02);assert.equal(pool.count,2);
const grass=createTireTrackPool({surfaceAt:()=>false});
grass.update(car,.02);grass.update({...car,z:1},.02);assert.equal(grass.count,0,'surface mask suppresses marks on lawn');
const braking=createTireTrackPool();
braking.update({...car,frontSlip:.7,rearSlip:0},.02);braking.update({...car,z:.5,frontSlip:.7,rearSlip:0},.02);
assert.equal(braking.active,2,'foot braking marks front wheels');
braking.clear();braking.update({...car,speed:0},.02);braking.update({...car,speed:0,z:1},.02);assert.equal(braking.count,0);
assert.throws(()=>createTireTrackPool({maxSegments:0}));assert.throws(()=>pool.update(car,NaN));
console.log('PASS tire marks: wheel selection, fade/expiry, bounded ring, teleport/release gap, surface mask, braking and stopped wheels');
