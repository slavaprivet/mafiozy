import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {createVehicleDamage} from './vehicle_damage.mjs';
const T=await import(pathToFileURL('D:/codex_release/artist13_hero_first_DEV_20260907/demo/vendor/build/three.module.js'));
const {createDemoCar}=await import('./car_drive.mjs');
const car=createDemoCar(T,T.BoxGeometry),damage=createVehicleDamage(T,car,{scene:new T.Group()});
const hood=car.shell.find(mesh=>mesh.name==='Hood_lid');
damage.impact({object:hood,damage:190,shotId:'ignite'});
damage.impact({object:hood,damage:100,shotId:'wreck'});
for(let i=0;i<90;i++)damage.update(.1);
const before=damage.debrisObject.children.map(mesh=>mesh.matrixWorld.clone());
for(let i=0;i<120;i++)damage.update(1/60);
const stats=damage.stats();
assert(stats.wrecked&&damage.state.wreckAge>=5,'wreck completes its original finite fire sequence');
assert.equal(stats.flames,0,'the original post-blast flames still finish before idling');
assert(stats.idleWreckUpdates>=120,'old settled wrecks stop their per-frame effect work');
assert.deepEqual(damage.debrisObject.children.map(mesh=>mesh.matrixWorld.clone()),before,'grounded real debris remains exactly where it settled');
damage.reset();assert.equal(damage.stats().idleWreckUpdates,0,'reset restores a live reusable vehicle');
damage.dispose();
console.log('PASS old wreck freezes only after fire fade and grounded debris complete');
