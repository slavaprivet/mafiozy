import assert from 'node:assert/strict';
import fs from 'node:fs';
import {registerHooks} from 'node:module';
import {pathToFileURL} from 'node:url';
const vendor=process.env.THREE_VENDOR_ROOT||'D:/codex_release/artist13_hero_first_DEV_20260907/demo/vendor';
registerHooks({resolve(s,c,next){return next(s==='three'?pathToFileURL(vendor+'/build/three.module.js').href:s,c);}});
const THREE=await import(pathToFileURL(vendor+'/build/three.module.js'));
const {GLTFLoader}=await import(pathToFileURL(vendor+'/addons/loaders/GLTFLoader.js'));
const {clone}=await import('./vendor/three_skeleton_utils.mjs');
const {createNpcPopulation}=await import('./npc_population.mjs');
const nativeFetch=globalThis.fetch;
globalThis.fetch=async(u,o)=>String(u).startsWith('file:')?{ok:true,arrayBuffer:async()=>{const b=fs.readFileSync(new URL(u));return b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength);}}:nativeFetch(u,o);
let focus={x:0,z:0},water=true;
const population=await createNpcPopulation({THREE,scene:new THREE.Scene(),loader:new GLTFLoader(),cloneSkeleton:clone,getFocus:()=>focus,waterAt:()=>water?{level:1,depth:1}:null,profile:true});
globalThis.fetch=nativeFetch;
const source={id:'clock_regression',r:0,c:40/4.1,weapon:'fists'};
population.sync([source],1);population.update(.04,1);
const actor=population.getActor(source.id),restore=actor.restoreSurfaceState;let restores=0;
actor.restoreSurfaceState=function(...args){restores++;return restore.apply(this,args);};
for(let frame=1;frame<=20;frame++)population.update(.04,1+frame*.16);
assert.equal(restores,0,'continuous visible far actor at 6.25 FPS must not serialize/restore its skins');
assert.equal(population.diagnostics().cpu.meanMs.poseRestores,0);
const wetAttributes=[];actor.object.traverse(o=>{const a=o.geometry?.attributes.aClothingWetness;if(a)wetAttributes.push(a);});
assert(wetAttributes.some(a=>a.array.some(v=>v>0)),'real clothing becomes wet');
const wetBefore=wetAttributes.map(a=>a.array.reduce((sum,v)=>sum+v,0));water=false;
population.receive(source.id,{id:'clock-death',confirmed:true,dead:true});
for(let frame=21;frame<=30;frame++)population.update(.04,1+frame*.16);
assert.equal(restores,0);assert.equal(actor.surface.state.kind,'dead','elapsed pose ticks cannot revive death');
assert(wetAttributes.some((a,i)=>a.array.reduce((sum,v)=>sum+v,0)<wetBefore[i]),'clothes continue drying');
focus={x:300,z:0};for(let frame=31;frame<=40;frame++)population.update(.04,1+frame*.16);
assert.equal(actor.object.visible,false);
focus={x:0,z:0};population.update(.04,1+41*.16);
assert.equal(restores,1,'real offscreen absence retains persistent-state catch-up');
assert.equal(actor.surface.state.kind,'dead');assert.equal(actor.object.visible,true);
population.update(.04,1+42*.16);assert.equal(restores,1,'returning actor resumes without repeated restoration');
population.dispose();console.log('PASS: low-FPS far pose cadence, wet/dry persistence, death, offscreen catch-up');
