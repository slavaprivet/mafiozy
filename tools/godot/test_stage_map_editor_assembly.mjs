import assert from 'node:assert/strict';
import {stageAssembly} from './stage_map_editor_assembly.mjs';
const result=await stageAssembly();
assert.equal(result.mode,'check');
assert.equal(result.destination,null);
assert.equal(result.resources,196);
assert.equal(result.assetBytes,30212460);
assert.equal(result.cacheCopied,false);
assert.equal(result.productionWired,false);
assert.equal(result.gpu,false);
assert.equal(new Set(result.files.map(x=>x.path)).size,result.files.length);
assert.equal(result.files.filter(x=>x.path.endsWith('.glb')).length,196);
assert.equal(result.files.some(x=>/(^|\/)\.godot(\/|$)|\.uid$|\.import$/.test(x.path)),false);
assert(result.files.some(x=>x.path==='scripts/map_editor/catalog_factory.gd'));
assert(result.files.some(x=>x.path==='scripts/map_editor/atomic_map_import.gd'));
assert(result.files.some(x=>x.path==='scripts/map_editor/editor_input_router.gd'));
assert(result.files.some(x=>x.path==='test_editor_input_router.gd'));
assert(result.files.some(x=>x.path==='test_document_full_catalog.gd'));
assert(result.files.some(x=>x.path==='test_editor_assembly.gd'));
assert(result.files.some(x=>x.path==='data/topology_for_placement.json'));
assert(result.files.every(x=>/^[a-f0-9]{64}$/.test(x.sha256)&&x.bytes>0));
await assert.rejects(stageAssembly({registryPerf:true}),/requires/);
await assert.rejects(stageAssembly({authoredPerf:true}),/requires/);
await assert.rejects(stageAssembly({procedural:true,transport:true,authoredPerf:true}),/requires/);
const combined=await stageAssembly({procedural:true,transport:true,registryPerf:true,authoredPerf:true});
assert.equal(combined.authoredPerf,true);
assert.equal(combined.registryPerf,true);
for(const path of ['authored_perf_receipt.json','authored_factory_perf.gd','authored_registry_perf.gd','test_full_all_perf.gd'])assert(combined.files.some(x=>x.path===path));
assert.equal(combined.files.some(x=>/(^|\/)\.godot(\/|$)|\.uid$|\.import$/.test(x.path)),false);
assert.equal(combined.productionWired,false);
assert.equal(combined.gpu,false);
assert.equal(combined.destination,null);
await assert.rejects(stageAssembly({pagedEditor:true}),/requires/);
await assert.rejects(stageAssembly({procedural:true,transport:true,registryPerf:true,pagedEditor:true}),/requires/);
const paged=await stageAssembly({procedural:true,transport:true,registryPerf:true,authoredPerf:true,pagedEditor:true});
assert.equal(paged.pagedEditor,true);
for(const path of ['paged_editor_receipt.json','paged_editor_panel.gd','paged_editor_controller.gd','test_paged_editor_controller.gd','test_full_paged_editor.gd'])assert(paged.files.some(x=>x.path===path));
assert.equal(paged.files.some(x=>/(^|\/)\.godot(\/|$)|\.uid$|\.import$/.test(x.path)),false);
assert.equal(paged.productionWired,false);
assert.equal(paged.gpu,false);
assert.equal(paged.destination,null);
console.log(JSON.stringify({suite:'source-only-assembly-stage',checks:43,resources:result.resources,files:result.files.length,combinedFiles:combined.files.length,pagedFiles:paged.files.length,gpu:false}));
