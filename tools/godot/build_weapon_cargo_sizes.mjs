import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';

// Deterministic, portable source pin: explicitly CRLF -> LF before hashing.
const root = process.cwd();
const input = 'godot/mafiozi_walk/assets/weapon_visual/manifest.json';
const text = fs.readFileSync(path.join(root, input), 'utf8').replace(/\r\n/g, '\n');
const manifest = JSON.parse(text);
const hash = crypto.createHash('sha256').update(text).digest('hex');
const rows = manifest.entries.filter(row => row.id !== 'none').map((row, index) => {
  const bounds = row.profile.bounds_native;
  const size = bounds.max.map((value, axis) => value - bounds.min[axis]);
  assert(size.every(value => Number.isFinite(value) && value > 0));
  return {id: row.id, index, bounds_native: bounds, size, volume: size.reduce((a, b) => a * b, 1)};
});
assert.equal(rows.length, 14);
const volume = rows.reduce((sum, row) => sum + row.volume, 0);
const minimum = 1, capacity = 100, remainderBudget = capacity - rows.length * minimum;
for (const row of rows) {
  row.quota = remainderBudget * row.volume / volume;
  row.units = minimum + Math.floor(row.quota);
  row.remainder = row.quota - Math.floor(row.quota);
}
const ranked = [...rows].sort((a, b) => b.remainder - a.remainder || a.index - b.index);
const left = capacity - rows.reduce((sum, row) => sum + row.units, 0);
for (let index = 0; index < left; index++) ranked[index].units++;
assert.equal(rows.reduce((sum, row) => sum + row.units, 0), 100);
for (const a of rows) for (const b of rows) if (a.volume > b.volume) assert(a.units >= b.units);
const costs = Object.fromEntries(rows.map(row => [row.id, row.units]));
const measurements = Object.fromEntries(rows.map(row => [row.id, {bounds_native: row.bounds_native, volume_native: row.volume}]));
const compartments = JSON.parse(fs.readFileSync(path.join(root, 'godot/mafiozi_walk/assets/vehicle_visual/compartments.json'), 'utf8'));
const cargo = compartments.profiles.compact_sedan.cargo_bounds;
const cargoSize = cargo.max.map((value, axis) => value - cargo.min[axis]);
const scale = .2, gap = .00501;
const floorStrip = [rows.reduce((sum, row) => sum + row.size[0] * scale, 0) + gap * (rows.length - 1), Math.max(...rows.map(row => row.size[1])) * scale, Math.max(...rows.map(row => row.size[2])) * scale];
assert(floorStrip.every((value, axis) => value < cargoSize[axis]));
const oracle = {schema: 'mafiozi.weapon-cargo-sizes/v1', manifest_sha256_lf: hash, hash_normalization: 'UTF-8 CRLF to LF', capacity, minimum, common_trunk_scale: scale, total_native_volume: volume, rows, floor_strip_proof: {vehicle: 'compact_sedan', cargo_bounds: cargo, cargo_size: cargoSize, dimensions: floorStrip, gap, all_orders: 'sum of widths plus 13 gaps fits one floor row; max height/depth fit; no stacking needed'}};
const gd = `extends RefCounted
## Generated by tools/godot/build_weapon_cargo_sizes.mjs from original bounds.
## Latest user requirement: one of each of all14 uses100; AK15 was an example.
const CAPACITY:=100
const MINIMUM:=1
const TRUNK_SCALE:=.2
const MANIFEST_SHA256_LF:="${hash}"
const HASH_NORMALIZATION:="UTF-8 CRLF to LF"
const ALLOCATION:="minimum1_then_largest_remainders_of86_by_native_AABB_volume"
const COSTS:Dictionary=${JSON.stringify(costs)}
const MEASUREMENTS:Dictionary=${JSON.stringify(measurements)}

static func metadata()->Dictionary:
\treturn {"capacity_units":CAPACITY,"capacity_source":"user_latest_all14_together100","costs":COSTS.duplicate(),"user_fixed_costs":{},"other_costs_source":"exact_model_volume_largest_remainders","allocation":ALLOCATION,"manifest_sha256_lf":MANIFEST_SHA256_LF,"hash_normalization":HASH_NORMALIZATION,"common_trunk_scale":TRUNK_SCALE,"corpse_reserved_units":100}
static func catalog_matches(catalog:RefCounted)->bool:
\tif catalog==null:return false
\tfor id:String in MEASUREMENTS:
\t\tif catalog.get_entry(id).get("profile",{}).get("bounds_native")!=MEASUREMENTS[id].bounds_native:return false
\treturn true
`;
const outputs = [['godot/mafiozi_walk/scripts/weapons/weapon_cargo_sizes.gd', gd], ['godot/mafiozi_walk/data/tests/weapon_cargo_sizes_oracle.json', JSON.stringify(oracle, null, 2) + '\n']];
for (const [relative, contents] of outputs) {
  const file = path.join(root, relative);
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n'), contents, relative + ' regeneration mismatch');
  else { fs.mkdirSync(path.dirname(file), {recursive: true}); fs.writeFileSync(file, contents); }
}
console.log(JSON.stringify({ok: true, check: process.argv.includes('--check'), costs, total: 100, floorStrip, cargoSize, manifest_sha256_lf: hash}));
