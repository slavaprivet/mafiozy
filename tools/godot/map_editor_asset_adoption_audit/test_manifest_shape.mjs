import {readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const here=fileURLToPath(new URL('.',import.meta.url));
const manifest=JSON.parse(await readFile(resolve(here,'manifest.json'),'utf8'));
const catalogRaw=await readFile(resolve(here,'../../../godot/mafiozi_walk/data/map_editor/catalog.json'));
const catalog=JSON.parse(catalogRaw);
function check(value,label){if(!value)throw Error(label);}
check(manifest.schema==='mafiozi.map-editor-asset-adoption-manifest/v2','schema');
check(manifest.resources.length===196&&manifest.placedTypes.length===33&&manifest.missingIds.length===188,'counts');
check(manifest.resourceFields.join(',')==='sha256,bytes,sourcePaths,placedObjects,assetIds,exactProductionPaths,canonicalPresent,declaredResPath,declaredResPathPresent','columns');
check(catalogRaw.length===manifest.catalog.bytes&&createHash('sha256').update(catalogRaw).digest('hex')===manifest.catalog.sha256,'catalog receipt');
const ids=manifest.resources.map(row=>row[0]);
check(new Set(ids).size===196&&ids.every((id,index)=>index===0||ids[index-1]<id),'unique sorted IDs');
check(manifest.resources.reduce((n,row)=>n+row[2].length,0)===201,'source path count');
check(manifest.resources.reduce((n,row)=>n+row[3],0)===242,'placed object count');
check(manifest.resources.filter(row=>row[5].length).length===8,'present count');
check(manifest.resources.filter(row=>row[6]).length===3,'canonical count');
const catalogById=new Map(catalog.resources.map(entry=>[entry.id,entry]));
check(manifest.resources.every(row=>row[7]===(catalogById.get(row[0])?.resPath??'')),'declared catalog path');
check(manifest.resources.every(row=>row[8]===(!!row[7]&&row[5].includes('godot/mafiozi_walk/'+row[7].slice('res://'.length)))),'declared exact production path');
check(manifest.counts.declaredResPaths===8&&manifest.counts.declaredResPathPresent===8&&manifest.counts.declaredResPathMissing===0&&manifest.counts.placedDeclaredResPathPresent===6,'declared path counts');
check(JSON.stringify(manifest.resources.filter(row=>!row[5].length).map(row=>row[0]))===JSON.stringify(manifest.missingIds),'exact missing set');
check(manifest.resources.filter(row=>!row[5].length).reduce((n,row)=>n+row[1],0)===manifest.counts.missingRawBytes,'missing byte sum');
check(manifest.placedTypes.every(row=>ids.includes(row.id)&&row.declaredResPathPresent===manifest.resources.find(resource=>resource[0]===row.id)[8])&&manifest.placedTypes.filter(row=>row.productionPresent).length===6,'placed types');
check(manifest.dependencies.length===13&&manifest.dependencies.every(row=>row.valid),'dependency receipts');
check(manifest.counts.externalGLBDependencies===0&&manifest.counts.sourceGLBValid===196,'source admission');
console.log(JSON.stringify({suite:'map-editor-asset-manifest-shape',checks:17,resources:196,missing:188,placedTypes:33}));
